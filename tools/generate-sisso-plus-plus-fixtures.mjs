// These are illustrative virtual data, not a claimed execution of SISSO++.
// Format pinned to upstream master 43b99110118a51b9f4983b02c8d781ae6f25456c.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { regressionEntries, multiTaskEntries, classificationEntries, classification2DEntries, logRegressionEntries, alternativeClassificationEntries } from "../test/sisso_plus_plus_fixtures.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../demo/sisso-plus-plus");
const JSZip = createRequire(import.meta.url)("../js/jszip.min.js");
const PP = createRequire(import.meta.url)("../js/sisso-plus-plus.js");
const examples = {
  regression: regressionEntries().map(e => e.path.endsWith("data.csv") ? { ...e, path: "data.csv" } : {
    ...e, path: e.path.replace("run/", "default/"),
    text: e.path.endsWith("sisso.json") ? `{
  // Shared input layout follows tests/exec_test/default/sisso.json.
  "data_file": "../data.csv", "data_file_relative_to_json": true,
  "property_key": "prop", "calc_type": "regression", "desc_dim": 2,
  "n_sis_select": 2, "max_rung": 2, "n_models_store": 1,
  "fix_intercept": false, "leave_out_inds": [2],
  "_synthetic": "Virtual data for importer verification; not generated by running SISSO++."
}\n` : e.text,
  }),
  "multi-task": multiTaskEntries(),
  "classification-1d": classificationEntries(),
  "classification-2d": classification2DEntries(),
  "log-regression": logRegressionEntries(),
  "log-multi-task": logRegressionEntries(true),
  "classification-davies-bouldin": alternativeClassificationEntries("Davies Bouldin"),
  "classification-silhouette": alternativeClassificationEntries("Sil Score"),
  "classification-calinski-harabasz": alternativeClassificationEntries("Calinski Harabasz"),
};
for (const [name, entries] of Object.entries(examples)) {
  const zip = new JSZip();
  for (const entry of entries) {
    const target = path.join(root, name, entry.path);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    let text = entry.text;
    if (entry.path.endsWith(".dat")) text = "# SYNTHETIC DEMONSTRATION — not an actual SISSO++ run\n" + text;
    if (entry.path.endsWith("sisso.json") && name !== "regression") {
      const config = JSON.parse(text);
      const csv = PP.parseCsv(entries.find(e => e.path.endsWith("data.csv")).text);
      const testFile = entries.find(e => /(?:^|\/)test_dim_/.test(e.path));
      const testIDs = new Set(testFile ? PP.parseModel(testFile).rows.map(r => r.id) : []);
      Object.assign(config, {
        data_file: "data.csv", desc_dim: config.desc_dim || Math.max(...entries.map(e => PP.modelName(e.path)).filter(Boolean).map(m => Number(m[2]))),
        n_sis_select: 2, max_rung: 2, n_residual: 1, n_models_store: 1,
        leave_out_inds: csv.slice(1).flatMap((row, i) => testIDs.has(row[0]) ? [i] : []),
        fix_intercept: false, param_opset: [],
      });
      config._synthetic = "Virtual data for importer verification; not generated by running SISSO++.";
      config.data_file_relative_to_json = true;
      text = JSON.stringify(config, null, 2) + "\n";
    }
    fs.writeFileSync(target, text);
    zip.file(name + "/" + entry.path, text, { date: new Date("2026-10-22T00:00:00Z") });
  }
  fs.writeFileSync(path.join(root, name + ".zip"), await zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" }));
}
console.log("Generated " + Object.keys(examples).length + " explicitly synthetic SISSO++ example folders and ZIP archives in " + root);
